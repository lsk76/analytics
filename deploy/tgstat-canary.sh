#!/usr/bin/env bash
# ============================================================================
# tgstat-canary.sh — щодня перевіряє, чи ще працює розбір ЖИВОГО tgstat.
#
# Тести на заготовках лишаються зеленими в день, коли tgstat перевіршує
# розмітку: парсери тихо починають віддавати порожнє, а видно це аж у порожньому
# дослідженні. Канарок ходить на живий сайт і кричить у лог одразу.
#
# Один прогін = 5 запитів до tgstat. ЧАСТІШЕ ЗА РАЗ НА ДОБУ НЕ СТАВИТИ: tgstat
# на частоту відповідає капчею, і тоді сервіс стає непридатним для всіх, доки
# людина не пройде її у VNC.
#
# Cron (раз на добу, час — щоб не збігався з бекапом):
#   17 5 * * * cd /opt/tg-event-analytics && bash deploy/tgstat-canary.sh >> backups/tgstat-canary.log 2>&1
#
# Код виходу: 0 — розмітка на місці або не перевірено (капча/розлогін);
#             1 — РОЗБІР ЗЛАМАВСЯ; 2 — не вдалося запустити перевірку.
# Підсумок лягає в Setting `tgstat_selftest_last`, тож його видно і в адмінці,
# і в `service_health` — не лише в цьому логу.
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/.."
DC="docker compose -f docker-compose.prod.yml"
STAMP="$(date -Is)"

out="$($DC exec -T web python manage.py mcp_rpc tgstat_selftest 2>&1)"
rc=$?
if [[ $rc -ne 0 ]]; then
  echo "$STAMP НЕ ЗАПУСТИЛОСЬ (rc=$rc): ${out: -600}"
  exit 2
fi

if grep -q "РОЗБІР ЗЛАМАВСЯ" <<<"$out"; then
  echo "$STAMP ⚠ РОЗБІР TGSTAT ЗЛАМАВСЯ"
  echo "$out"
  echo "$STAMP що робити: tgstat_selftest покаже, яка перевірка впала; сиру сторінку"
  echo "$STAMP дивитись через /raw?path=…, парсери — tgstat_service/app/parse.py,"
  echo "$STAMP заготовки тестів — tgstat_service/tests/fixtures/."
  exit 1
fi

if grep -q "не перевірено" <<<"$out"; then
  # Капча чи розлогін — це не поломка розбору, але й не «усе добре»: сервіс
  # стоїть, доки людина не зайде у VNC.
  echo "$STAMP — НЕ перевірено (сесія tgstat потребує людини): $(grep -m1 'підсумок\|стан сесії' <<<"$out")"
  exit 0
fi

echo "$STAMP ✓ розмітка на місці ($(grep -m1 'підсумок' <<<"$out" | tr -s ' '))"
exit 0
