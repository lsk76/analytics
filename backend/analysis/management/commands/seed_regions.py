class Command(BaseCommand):
    help = "Seed RF federal subjects"

    def handle(self, *args, **opts):
        groups = [(REPUBLICS, "республіка"), (KRAIS, "край"), (OBLASTS, "область"),
                  (CITIES, "місто"), (AO, "ао")]
        n = 0
        for names, kind in groups:
            for name in names:
                _, created = Region.objects.get_or_create(name=name, defaults={"kind": kind})
                n += int(created)
        self.stdout.write(self.style.SUCCESS(
            f"Суб'єктів РФ у БД: {Region.objects.count()} (нових: {n})"))
