# =========================================================================
# User-prompt template — feeds N comments per call
# =========================================================================

def build_user_prompt(comments: list[dict]) -> str:
    """Build the user message for a batch.

    Each comment dict must have: id (int), text (str), chat (str), region (str).
    The chat/region context helps the model resolve regional officials.
    """
    lines = []
    for i, c in enumerate(comments):
        chat = c.get("chat") or "-"
        region = c.get("region") or "-"
        text = (c.get("text") or "").strip().replace("\n", " ")[:1500]
        lines.append(f"[{i}] chat=@{chat} | region={region}\n{text}")
    return "\n\n".join(lines)


